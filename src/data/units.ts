/** A review unit at the end of each stage, built from that stage's lessons. */
function checkpoint(stage: Stage, units: Def[]): Def {
  return {
    id: `repaso-${stage.num}`,
    stage: stage.num,
    level: stage.level,
    title: `Repaso: ${stage.title}`,
    titleEn: `Stage ${stage.num} review`,
    checkpoint: true,
    explain: [
      `This review mixes everything from stage ${stage.num}: ${units.map((u) => u.titleEn.toLowerCase()).join('; ')}.`,
      'Pass the drills to finish the stage. If something feels shaky, go back to that lesson first.',
    ],
    p: units.flatMap((u) => u.p.slice(0, 2)),
    talk: {
      goalEn: `A mixed review conversation using everything from stage ${stage.num}.`,
      opener: stage.opener,
      openerEn: stage.openerEn,
    },
  };
}

function build(): Unit[] {
  const out: Unit[] = [];
  let num = 0;
  for (const stage of STAGES) {
    const defs = DEFS.filter((d) => d.stage === stage.num);
    for (const d of [...defs, checkpoint(stage, defs)]) {
      const { p, ...rest } = d;
      out.push({ ...rest, num: d.checkpoint ? num : ++num, phrases: p.map(([es, en]) => ({ es, en })) });
    }
  }
  return out;
}

export const UNITS: Unit[] = build();

/** The conversation for a unit: its scenario or lesson chat, aimed at what the unit teaches. */
export function unitScenario(unit: Unit): Scenario {
  const focus = `${unit.titleEn}. ${unit.explain.join(' ')}`;
  const linked = SCENARIOS.find((s) => s.id === unit.scenario);
  if (linked) return { ...linked, focus };
  const t = unit.talk!;
  return {
    id: `lesson-${unit.id}`,
    title: unit.title,
    titleEn: unit.titleEn,
    emoji: unit.checkpoint ? '⭐' : '📘',
    role: t.role ?? 'Sofi, your friendly tutor from Mexico City, chatting one-on-one',
    setting: t.role ? 'A role-play phone call.' : 'A relaxed one-on-one lesson chat on video.',
    goal: t.goalEn,
    goalEn: t.goalEn,
    opener: t.opener,
    openerEn: t.openerEn,
    minLevel: unit.level,
    focus,
  };
}
